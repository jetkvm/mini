#!/usr/bin/env bash
# Makes the test release key again: an Ed25519 primary key that certifies and
# an Ed25519 signing subkey, as the JetKVM release key has them. A bench build
# (JETKVM_MOCK_CLOUD) trusts this key for an update from a stand-in update
# server, and the stand-in servers of tools/ sign with it. Its private half is
# in the repository, so tools/release_r2.sh refuses an image that names it.
#
# Writes, beside this script:
#   test-release-key.asc         the public key, as a keyserver serves it
#   test-release-key.secret.asc  the private key, for GnuPG
#   test-release-key.json        the fingerprints and the signing subkey's
#                                private key, for the tools that sign in Node
#   ../jetkvm_ota_test_key.h     the fingerprint, for the bench build
#
# A new key changes the fingerprint in every bench image: the Minis of the
# benches then need images of the new build before they take a stand-in update.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
export GNUPGHOME="$(mktemp -d)"
trap 'gpgconf --kill all; rm -rf "$GNUPGHOME"' EXIT
gpg_batch=(gpg --batch --quiet --pinentry-mode loopback --passphrase "")

"${gpg_batch[@]}" --quick-gen-key "JetKVM Mini TEST release key (private key is public)" ed25519 cert never
root="$(gpg --list-keys --with-colons | awk -F: '/^fpr:/ { print $10; exit }')"
"${gpg_batch[@]}" --quick-add-key "$root" ed25519 sign never
signing="$(gpg --list-keys --with-colons | awk -F: '/^fpr:/ { print $10 }' | sed -n 2p)"

gpg --armor --export "$root" > "$here/test-release-key.asc"
"${gpg_batch[@]}" --armor --export-secret-keys "$root" > "$here/test-release-key.secret.asc"

# The signing subkey's private key: the 32 octets after the public part of
# its secret subkey packet (RFC 9580 5.5.3), which GnuPG exports unprotected
# for a key without a passphrase.
"${gpg_batch[@]}" --export-secret-subkeys "$signing!" | python3 -c '
import json, sys
data = sys.stdin.buffer.read()
root, signing = sys.argv[1], sys.argv[2]
offset, seed = 0, None
while offset < len(data):
    ctb = data[offset]
    assert ctb & 0xC0 == 0xC0 or ctb & 0x80, "not an OpenPGP packet"
    if ctb & 0x40:
        tag, first = ctb & 0x3F, data[offset + 1]
        if first < 192:
            size, head = first, 2
        elif first < 224:
            size, head = ((first - 192) << 8) + data[offset + 2] + 192, 3
        else:
            size, head = int.from_bytes(data[offset + 2:offset + 6], "big"), 6
    else:
        tag, kind = (ctb >> 2) & 0x0F, ctb & 3
        octets = (1, 2, 4)[kind]
        size, head = int.from_bytes(data[offset + 1:offset + 1 + octets], "big"), 1 + octets
    body = data[offset + head:offset + head + size]
    offset += head + size
    if tag != 7:
        continue
    # Version 4, EdDSA with the Ed25519 curve: 6 + 10 + 2 + 33 octets of
    # public key, then the usage octet and the private key as an MPI.
    public = 6 + 10 + 2 + 33
    assert body[0] == 4 and body[5] == 22 and body[public] == 0, "an unprotected Ed25519 subkey is expected"
    bits = int.from_bytes(body[public + 1:public + 3], "big")
    octets = (bits + 7) // 8
    seed = body[public + 3:public + 3 + octets].rjust(32, b"\0")
assert seed is not None, "no secret subkey"
json.dump({"rootFingerprint": root, "signingFingerprint": signing, "signingPrivateKey": seed.hex()}, sys.stdout, indent=2)
print()
' "$root" "$signing" > "$here/test-release-key.json"

cat > "$here/../jetkvm_ota_test_key.h" <<EOF
/*
 * SPDX-FileCopyrightText: 2026
 * SPDX-License-Identifier: MIT
 */

/* Generated by test_key/make_test_key.sh. The fingerprint of the test release
 * key, whose private half is in the repository (test_key/). Only a bench
 * build includes this file (JETKVM_MOCK_CLOUD in jetkvm_ota.c), and
 * tools/release_r2.sh refuses an image that contains this text. */

#pragma once

#define JETKVM_OTA_TEST_RELEASE_KEY_FINGERPRINT "$root"
EOF
echo "test release key $root, signing subkey $signing"
