static int failures;

static void expect_bytes(const char *name, const uint8_t *got, const uint8_t *want, size_t len) {
    if (memcmp(got, want, len) != 0) {
        printf("FAIL %s\n", name);
        failures++;
    } else {
        printf("ok   %s\n", name);
    }
}

