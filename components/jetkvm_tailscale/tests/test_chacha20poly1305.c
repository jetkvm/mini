static void test_stream_2_4_2(size_t offset) {
    uint8_t key[32];
    for (int i = 0; i < 32; i++) key[i] = (uint8_t)i;
    static _Alignas(4) uint8_t buffer[128 + 4];
    struct chacha20_ctx ctx;
    chacha20_init(&ctx, key, 0x4a000000ULL);
    ctx.state[12] = 1;
    memcpy(buffer + offset, plaintext_2_4_2, 114);
    chacha20(&ctx, buffer + offset, buffer + offset, 114);
    char name[64];
    snprintf(name, sizeof name, "RFC 8439 2.4.2 stream, offset %zu", offset);
    expect_bytes(name, buffer + offset, ciphertext_2_4_2, 114);
}

static void test_aead_a5(size_t offset) {
    static _Alignas(4) uint8_t sealed[265 + 16 + 4];
    static _Alignas(4) uint8_t opened[265 + 4];
    char name[64];

    memcpy(sealed + offset, sealed_a5, sizeof sealed_a5);
    snprintf(name, sizeof name, "RFC 8439 A.5 decrypt, offset %zu", offset);
    if (!chacha20poly1305_decrypt(opened + offset, sealed + offset, sizeof sealed_a5, ad_a5,
                                  sizeof ad_a5, nonce_a5, key_a5)) {
        printf("FAIL %s: tag rejected\n", name);
        failures++;
    } else {
        expect_bytes(name, opened + offset, (const uint8_t *)plaintext_a5, 265);
    }

    memcpy(opened + offset, plaintext_a5, 265);
    chacha20poly1305_encrypt(sealed + offset, opened + offset, 265, ad_a5, sizeof ad_a5,
                             nonce_a5, key_a5);
    snprintf(name, sizeof name, "RFC 8439 A.5 encrypt, offset %zu", offset);
    expect_bytes(name, sealed + offset, sealed_a5, sizeof sealed_a5);

    sealed[offset + 3] ^= 1;
    snprintf(name, sizeof name, "RFC 8439 A.5 altered ciphertext, offset %zu", offset);
    if (chacha20poly1305_decrypt(opened + offset, sealed + offset, sizeof sealed_a5, ad_a5,
                                 sizeof ad_a5, nonce_a5, key_a5)) {
        printf("FAIL %s: accepted\n", name);
        failures++;
    } else {
        printf("ok   %s\n", name);
    }
}

int main(void) {
    /* Offset 0 takes the word path for whole blocks; offsets 1 and 3 take the byte path. */
    for (size_t offset = 0; offset < 4; offset++) {
        test_stream_2_4_2(offset);
        test_aead_a5(offset);
    }
    if (failures) {
        printf("%d failures\n", failures);
        return 1;
    }
    return 0;
}
