#!/usr/bin/env python3
"""Generate the Mini's time zone table from the build machine's tzdata.

    tools/timezones/generate.py [--zoneinfo DIR] [--check]

Each compiled zone file (TZif) ends with one line: the POSIX TZ rule that
gives the zone's time after the last change in the file, for example
"CET-1CEST,M3.5.0,M10.5.0/3". The table maps each zone name to that rule, so
the firmware needs no zone files. components/jetkvm_timezone reads a rule
without daylight time, or with both changes in the form Mm.w.d[/time]; the
generator stops at a rule of another form.

A rule cannot describe a zone whose changes follow no fixed day of a month
(Morocco changes its clocks around Ramadan), or one with a change that is
still to come and differs from the rule. The generator compares each rule
with the zone file over the five years from --since, through the C library,
and names the zones that differ in the header.

--check fails when the committed header is not what this machine's tzdata
gives. It is for a machine with the tzdata version that the header names.
"""
from datetime import datetime, timezone
from pathlib import Path
import argparse
import os
import re
import sys
import time
import zoneinfo

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / 'components/jetkvm_timezone/jetkvm_timezone_table.h'
# The machine's own zone and tzdata's placeholder are not zones to select.
NOT_ZONES = {'localtime', 'Factory', 'posixrules'}
OFFSET = r'[-+]?\d{1,3}(?::\d{1,2}(?::\d{1,2})?)?'
NAME = r'(?:[A-Za-z]{3,}|<[-+A-Za-z0-9]{3,}>)'
CHANGE = rf'M\d{{1,2}}\.[1-5]\.[0-6](?:/{OFFSET})?'
RULE = re.compile(rf'{NAME}{OFFSET}(?:{NAME}(?:{OFFSET})?,{CHANGE},{CHANGE})?')
YEARS = 5


def zone_files(directory):
    """name -> path of each zone file below directory, without the posix/ and right/ copies."""
    found = {}
    for path in sorted(directory.rglob('*')):
        name = path.relative_to(directory).as_posix()
        if not path.is_file() or name.split('/')[0] in ('posix', 'right') or name in NOT_ZONES:
            continue
        with path.open('rb') as file:
            if file.read(4) == b'TZif':
                found[name] = path
    return found


def rule_of(path):
    data = path.read_bytes()
    if not data.endswith(b'\n'):
        raise SystemExit(f'{path}: no rule line; the file is TZif version 1')
    rule = data[:-1].rsplit(b'\n', 1)[-1].decode('ascii')
    if not RULE.fullmatch(rule):
        raise SystemExit(f'{path}: components/jetkvm_timezone does not read the rule "{rule}"')
    return rule


def differing(zones, rules, since):
    """The zones whose rule gives another offset than the zone file in the YEARS years from since."""
    begin = int(since.timestamp())
    end = int(since.replace(year=since.year + YEARS).timestamp())
    samples = range(begin, end, 6 * 3600)
    previous = os.environ.get('TZ')
    wrong = []
    try:
        by_rule = {}
        for name, rule in rules.items():
            by_rule.setdefault(rule, []).append(name)
        for rule, names in by_rule.items():
            os.environ['TZ'] = rule
            time.tzset()
            offsets = [time.localtime(sample).tm_gmtoff for sample in samples]
            for name in names:
                with zones[name].open('rb') as file:
                    zone = zoneinfo.ZoneInfo.from_file(file)
                if any(datetime.fromtimestamp(sample, zone).utcoffset().total_seconds() != offset
                       for sample, offset in zip(samples, offsets)):
                    wrong.append(name)
    finally:
        if previous is None:
            os.environ.pop('TZ', None)
        else:
            os.environ['TZ'] = previous
        time.tzset()
    return sorted(wrong)


def version_of(directory):
    """tzdata's version, from the first line of tzdata.zi ("# version 2026f")."""
    try:
        first = (directory / 'tzdata.zi').read_text().splitlines()[0]
    except (OSError, IndexError):
        return 'unknown'
    return first.removeprefix('# version ').strip() or 'unknown'


def render(directory, since):
    zones = zone_files(directory)
    if not zones:
        raise SystemExit(f'no zone files in {directory}')
    rules = {name: rule_of(path) for name, path in zones.items()}
    wrong = differing(zones, rules, since)
    text = (f'/* Generated by tools/timezones/generate.py from tzdata {version_of(directory)}; do not edit by hand.\n'
            f' * {len(rules)} zones, sorted by name for the search in jetkvm_timezone.c.\n')
    if wrong:
        text += (f' * The rule differs from the zone file at some time in the {YEARS} years from {since:%Y-%m-%d}\n'
                 f' * for: {", ".join(wrong)}.\n')
    text += ' */\nstatic const struct { const char *name, *rule; } s_timezones[] = {\n'
    # Python sorts str by code point, which for ASCII is the order of strcmp().
    for name in sorted(rules):
        text += f'    {{"{name}", "{rules[name]}"}},\n'
    return text + '};\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--zoneinfo', type=Path, default=Path('/usr/share/zoneinfo'))
    parser.add_argument('--output', type=Path, default=OUTPUT)
    parser.add_argument('--since', default=f'{datetime.now(timezone.utc):%Y-%m-%d}',
                        help='first day (YYYY-MM-DD, not 29 February) of the years in which the rules are '
                             'compared with the zone files; today by default')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = render(args.zoneinfo, datetime.strptime(args.since, '%Y-%m-%d').replace(tzinfo=timezone.utc))
    if args.check:
        if args.output.read_text() != text:
            sys.exit(f'{args.output} is not what {args.zoneinfo} gives; run tools/timezones/generate.py')
    else:
        args.output.write_text(text)
